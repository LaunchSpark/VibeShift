"""Retrain Laya on the combined W=5 training split and evaluate against prior runs."""

from __future__ import annotations

import argparse
import json
import random
from collections import Counter
from pathlib import Path
from typing import Any

from evaluation import train_combined_w5 as combined
from evaluation.common.labels import LABELS
from evaluation.w5_model_comparison import evaluate_model

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "evaluation" / "results" / "combined_w5_20261126_laya_retrained"
RUN_ROOT = ROOT / "operations" / "data" / "combined_w5_20261126_laya_retrained"
PREVIOUS_RESULTS = ROOT / "evaluation" / "results" / "combined_w5_20261126"
SEED = 4240


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--epochs", type=int, default=4)
    parser.add_argument("--batch-size", type=int, default=8)
    parser.add_argument("--inference-batch-size", type=int, default=8)
    parser.add_argument("--bootstrap-iterations", type=int, default=1000)
    args = parser.parse_args()
    if min(args.epochs, args.batch_size, args.inference_batch_size) < 1:
        parser.error("epoch and batch-size values must be positive")

    all_labels, messages, _machine_rows, _human_labels, split, _conversation_by_id = combined._load_data()
    message_by_id = {str(row["id"]): row for row in messages}
    texts = {row["id"]: combined.w5_text(message_by_id[row["id"]]) for row in all_labels}
    train_rows = [row for row in all_labels if split[row["id"]] == "train"]
    test_rows = [row for row in all_labels if split[row["id"]] == "test"]

    # Match the original run's deterministic, stratified 10% training calibration subset.
    calibration_rows = []
    for source, seed_offset in (("human", 11), ("machine", 29)):
        source_rows = [row for row in train_rows if row["source"] == source]
        rng = random.Random(SEED + seed_offset)
        for label in LABELS:
            class_rows = [row for row in source_rows if row["label"] == label]
            if class_rows:
                count = min(len(class_rows), max(1, round(len(class_rows) * 0.10)))
                calibration_rows.extend(rng.sample(class_rows, count))
    selected_rows = calibration_rows + test_rows
    eval_split = {row["id"]: "train" for row in calibration_rows}
    eval_split.update({row["id"]: "test" for row in test_rows})

    RESULTS.mkdir(parents=True, exist_ok=True)
    RUN_ROOT.mkdir(parents=True, exist_ok=True)
    new_predictions_path = RESULTS / "predictions_learned_behavior_laya.jsonl"
    new_predictions, training_metadata = combined._train_laya(
        train_rows, selected_rows, texts, RUN_ROOT / "laya", args.epochs,
        args.batch_size, args.inference_batch_size, prediction_path=new_predictions_path,
    )

    model_predictions = {
        "pretrained_bot_laya": combined.read_jsonl(
            PREVIOUS_RESULTS / "predictions_pretrained_bot_laya.jsonl"),
        "learned_behavior_laya_previous": combined.read_jsonl(
            PREVIOUS_RESULTS / "predictions_learned_behavior_laya_calibration_test.jsonl"),
        "learned_behavior_laya_retrained": new_predictions,
    }
    partitions = {
        "combined": (selected_rows, eval_split),
        "human_only": ([r for r in selected_rows if r["source"] == "human"],
                        {r["id"]: eval_split[r["id"]] for r in selected_rows if r["source"] == "human"}),
        "machine_only": ([r for r in selected_rows if r["source"] == "machine"],
                          {r["id"]: eval_split[r["id"]] for r in selected_rows if r["source"] == "machine"}),
    }
    message_lookup = {str(row["id"]): row for row in messages}
    report: dict[str, Any] = {
        "protocol": {
            "seed": SEED,
            "human_split": "StratifiedGroupKFold 5-fold, first fold; group=conversation",
            "machine_split": "StratifiedGroupKFold 5-fold, first fold; group=conversation",
            "human_train_rows": sum(r["source"] == "human" for r in train_rows),
            "human_test_rows": sum(r["source"] == "human" for r in test_rows),
            "machine_train_rows": sum(r["source"] == "machine" for r in train_rows),
            "machine_test_rows": sum(r["source"] == "machine" for r in test_rows),
            "combined_training_rows": len(train_rows),
            "tau_calibration_rows": len(calibration_rows),
            "tau_calibration_note": "same deterministic stratified training subset as the original combined evaluation",
            "train_test_conversation_overlap": [],
            "test_label_counts": dict(Counter(r["label"] for r in test_rows)),
        },
        "weak_label_warning": (
            "Machine labels were generated by pretrained Laya. Machine-only scores are agreement "
            "with pseudo-labels; the human-only held-out partition is the primary quality estimate."
        ),
        "model_metadata": {
            "pretrained_bot_laya": {"source": "original combined evaluation baseline"},
            "learned_behavior_laya_previous": {"source": "original combined evaluation, one-epoch checkpoint"},
            "learned_behavior_laya_retrained": training_metadata,
        },
        "results": {},
        "run": {"epochs": args.epochs, "batch_size": args.batch_size,
                "gradient_training_rows": len(train_rows),
                "results_directory": RESULTS.relative_to(ROOT).as_posix(),
                "checkpoint_directory": (RUN_ROOT / "laya" / "learned_behavior_laya").relative_to(ROOT).as_posix()},
    }
    for model_name, predictions in model_predictions.items():
        report["results"][model_name] = {}
        for partition_name, (labels, partition_split) in partitions.items():
            prediction_ids = {row["id"] for row in labels}
            partition_predictions = [row for row in predictions if row["id"] in prediction_ids]
            result = evaluate_model(
                model_name, labels, [message_lookup[row["id"]] for row in labels],
                partition_split, partition_predictions, args.bootstrap_iterations,
            )
            result.pop("tau_sweep", None)
            result.pop("test_confusion", None)
            report["results"][model_name][partition_name] = result

    report_path = RESULTS / "metrics.json"
    report_path.write_text(json.dumps(report, indent=2, default=str) + "\n", encoding="utf-8")
    lines = [
        "# Combined W=5 Laya Retraining",
        "",
        "Laya's training framework fine-tuned the pretrained checkpoint on the combined human and machine training split. Each metric below is recalculated using the same held-out split and training-only tau calibration subset as the prior evaluation.",
        "",
        "Machine-only results measure agreement with pretrained-Laya pseudo-labels; use human-only results as the primary quality comparison.",
        "",
        "| Model | Partition | N | Accuracy | Balanced accuracy | Macro F1 | Cohen's kappa | Tau |",
        "|---|---|---:|---:|---:|---:|---:|---:|",
    ]
    for model_name, by_partition in report["results"].items():
        for partition_name, result in by_partition.items():
            m = result["test"]
            lines.append(
                f"| {model_name} | {partition_name} | {m['n']} | {m['accuracy']:.3f} | "
                f"{m['balanced_accuracy']:.3f} | {m['macro_f1']:.3f} | "
                f"{m['cohen_kappa']:.3f} | {result['selected_tau']:.4f} |"
            )
    (RESULTS / "evaluation_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Saved retrained checkpoint to {report['run']['checkpoint_directory']}", flush=True)
    print(f"Saved evaluation report to {RESULTS}", flush=True)
    for name in model_predictions:
        human = report["results"][name]["human_only"]
        metrics = human["test"]
        print(
            f"{name}: human-only n={metrics['n']} accuracy={metrics['accuracy']:.3f} "
            f"balanced_accuracy={metrics['balanced_accuracy']:.3f} "
            f"macro_f1={metrics['macro_f1']:.3f} kappa={metrics['cohen_kappa']:.3f}",
            flush=True,
        )


if __name__ == "__main__":
    main()
